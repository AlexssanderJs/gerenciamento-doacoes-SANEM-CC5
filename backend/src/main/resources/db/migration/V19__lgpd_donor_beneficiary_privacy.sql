-- V19 - LGPD para doadores e beneficiários (RNF04).
-- Registra base legal, finalidade, consentimento (quando aplicável) e anonimização
-- dos titulares cujos dados pessoais são tratados pela organização.

ALTER TABLE donor
    ADD COLUMN legal_basis VARCHAR(30) NULL,
    ADD COLUMN privacy_purpose VARCHAR(255) NULL,
    ADD COLUMN privacy_consent BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN privacy_consent_at TIMESTAMP(6) NULL,
    ADD COLUMN privacy_consent_version VARCHAR(50) NULL,
    ADD COLUMN anonymized_at TIMESTAMP(6) NULL;

ALTER TABLE beneficiary
    ADD COLUMN legal_basis VARCHAR(30) NULL,
    ADD COLUMN privacy_purpose VARCHAR(255) NULL,
    ADD COLUMN privacy_consent BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN privacy_consent_at TIMESTAMP(6) NULL,
    ADD COLUMN privacy_consent_version VARCHAR(50) NULL,
    ADD COLUMN anonymized_at TIMESTAMP(6) NULL;

ALTER TABLE donor
    ADD CONSTRAINT chk_donor_legal_basis CHECK (legal_basis IS NULL OR legal_basis IN
        ('CONSENT', 'LEGITIMATE_INTEREST', 'LEGAL_OBLIGATION', 'PUBLIC_POLICY'));
ALTER TABLE beneficiary
    ADD CONSTRAINT chk_beneficiary_legal_basis CHECK (legal_basis IS NULL OR legal_basis IN
        ('CONSENT', 'LEGITIMATE_INTEREST', 'LEGAL_OBLIGATION', 'PUBLIC_POLICY'));

-- Trilha de auditoria dos tratamentos/consentimentos de titulares sem conta de acesso.
CREATE TABLE data_subject_privacy_event (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type VARCHAR(20) NOT NULL,
    subject_id BIGINT NOT NULL,
    event_type VARCHAR(20) NOT NULL,
    legal_basis VARCHAR(30),
    consent_given BOOLEAN NOT NULL DEFAULT FALSE,
    policy_version VARCHAR(50),
    occurred_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by_user_id INTEGER,
    CONSTRAINT fk_subject_event_user FOREIGN KEY (recorded_by_user_id) REFERENCES app_user(user_id)
        ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT chk_subject_event_type CHECK (subject_type IN ('DONOR', 'BENEFICIARY')),
    CONSTRAINT chk_subject_event_kind CHECK (event_type IN ('RECORDED', 'UPDATED', 'ANONYMIZED'))
);

CREATE INDEX idx_subject_event_subject
    ON data_subject_privacy_event (subject_type, subject_id, occurred_at DESC);
